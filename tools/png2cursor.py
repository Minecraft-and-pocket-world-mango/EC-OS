#!/usr/bin/env python3
"""Convert system/pic/cursor.png into system/cursor_data.h.

The PNG is decoded by hand (zlib is in the stdlib) so no third-party
dependency is required. Every opaque pixel becomes either a black or a
white dot; transparent pixels are skipped. The result is emitted as two
uint16_t bitfields per scanline (shape + colour) that mouse.c blits.
"""

import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_PNG = os.path.join(ROOT, "system", "pic", "cursor.png")
DEFAULT_OUT = os.path.join(ROOT, "system", "cursor_data.h")


def paeth(a, b, c):
    p = a + b - c
    pa = abs(p - a)
    pb = abs(p - b)
    pc = abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c


def decode_png(path):
    with open(path, "rb") as fh:
        data = fh.read()

    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit("%s is not a PNG file" % path)

    pos = 8
    width = height = bitdepth = colortype = None
    idat = b""
    while pos + 8 <= len(data):
        length = struct.unpack(">I", data[pos:pos + 4])[0]
        ctype = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if ctype == b"IHDR":
            width, height, bitdepth, colortype = struct.unpack(">IIBB", body[:10])
        elif ctype == b"IDAT":
            idat += body
        elif ctype == b"IEND":
            break

    if bitdepth != 8 or colortype not in (2, 6):
        raise SystemExit("cursor.png must be 8-bit RGB or RGBA")

    channels = 4 if colortype == 6 else 3
    raw = zlib.decompress(idat)
    stride = width * channels
    prev = bytearray(stride)
    rows = []
    p = 0
    for _ in range(height):
        ftype = raw[p]
        p += 1
        line = bytearray(raw[p:p + stride])
        p += stride
        for i in range(stride):
            x = line[i]
            a = line[i - channels] if i >= channels else 0
            b = prev[i]
            c = prev[i - channels] if i >= channels else 0
            if ftype == 1:
                x = (x + a) & 0xFF
            elif ftype == 2:
                x = (x + b) & 0xFF
            elif ftype == 3:
                x = (x + ((a + b) >> 1)) & 0xFF
            elif ftype == 4:
                x = (x + paeth(a, b, c)) & 0xFF
            line[i] = x
        rows.append(line)
        prev = line

    pixels = []
    for y in range(height):
        line = rows[y]
        row = []
        for x in range(width):
            i = x * channels
            r = line[i]
            g = line[i + 1]
            bl = line[i + 2]
            al = line[i + 3] if channels == 4 else 255
            row.append((r, g, bl, al))
        pixels.append(row)

    return width, height, pixels, channels


def downsample(rows, width, height, factor):
    """Nearest-neighbour shrink by an integer factor.

    Within each source block the most opaque pixel wins, so thin parts of the
    cursor survive the reduction instead of disappearing.
    """
    out_w = width // factor
    out_h = height // factor
    out = []
    for oy in range(out_h):
        row = []
        for ox in range(out_w):
            best = (0, 0, 0, -1)
            for dy in range(factor):
                for dx in range(factor):
                    px = rows[oy * factor + dy][ox * factor + dx]
                    if px[3] > best[3]:
                        best = px
            row.append(best)
        out.append(row)
    return out_w, out_h, out


def main():
    png = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_PNG
    out = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT
    factor = int(sys.argv[3]) if len(sys.argv) > 3 else 2

    width, height, rows, channels = decode_png(png)

    if factor > 1:
        width, height, rows = downsample(rows, width, height, factor)

    shape = [0] * height
    white = [0] * height
    for y in range(height):
        s = 0
        w = 0
        for x in range(width):
            r, g, b, a = rows[y][x]
            if a < 128:
                continue
            s |= 1 << x
            luma = (r * 30 + g * 59 + b * 11) // 100
            if luma >= 128:
                w |= 1 << x
        shape[y] = s
        white[y] = w

    lines = []
    lines.append("/* Auto-generated by tools/png2cursor.py from %s. Do not edit. */"
                 % os.path.relpath(png, ROOT).replace("\\", "/"))
    lines.append("#ifndef EC_CURSOR_DATA_H")
    lines.append("#define EC_CURSOR_DATA_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("#define CURSOR_W %d" % width)
    lines.append("#define CURSOR_H %d" % height)
    lines.append("")
    lines.append("static const uint16_t cursor_shape[CURSOR_H] = {")
    lines.append("    " + ", ".join("0x%04X" % v for v in shape))
    lines.append("};")
    lines.append("")
    lines.append("static const uint16_t cursor_white[CURSOR_H] = {")
    lines.append("    " + ", ".join("0x%04X" % v for v in white))
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    lines.append("")

    with open(out, "w", newline="\n") as fh:
        fh.write("\n".join(lines))

    print("  cursor %dx%d -> %s" % (width, height, os.path.relpath(out, ROOT)))


if __name__ == "__main__":
    main()
