#!/usr/bin/env python3
"""Convert system/pic/file.png into system/icon_data.c/.h.

The PNG is decoded by hand (zlib only, no third-party deps) and area-averaged
down to a small RGBA sprite that the kernel blits with gfx_blend(). Each pixel
is packed as 0xAARRGGBB. file.png is used as the folder icon because the
project ships no separate folder.png.
"""

import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_PNG = os.path.join(ROOT, "system", "pic", "file.png")
OUT_C = os.path.join(ROOT, "system", "icon_data.c")
OUT_H = os.path.join(ROOT, "system", "icon_data.h")

ICON_W = 64
ICON_H = 64


def paeth(a, b, c):
    p = a + b - c
    pa = abs(p - a)
    pb = abs(p - b)
    pc = abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c


def decode_png(path):
    with open(path, "rb") as fh:
        data = fh.read()

    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit("%s is not a PNG file" % path)

    pos = 8
    width = height = bitdepth = colortype = None
    idat = b""
    while pos + 8 <= len(data):
        length = struct.unpack(">I", data[pos:pos + 4])[0]
        ctype = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if ctype == b"IHDR":
            width, height, bitdepth, colortype = struct.unpack(">IIBB", body[:10])
        elif ctype == b"IDAT":
            idat += body
        elif ctype == b"IEND":
            break

    if bitdepth != 8 or colortype not in (2, 6):
        raise SystemExit("%s must be 8-bit RGB or RGBA" % path)

    channels = 4 if colortype == 6 else 3
    raw = zlib.decompress(idat)
    stride = width * channels
    prev = bytearray(stride)
    rows = []
    p = 0
    for _ in range(height):
        ftype = raw[p]
        p += 1
        line = bytearray(raw[p:p + stride])
        p += stride
        for i in range(stride):
            x = line[i]
            a = line[i - channels] if i >= channels else 0
            b = prev[i]
            c = prev[i - channels] if i >= channels else 0
            if ftype == 1:
                x = (x + a) & 0xFF
            elif ftype == 2:
                x = (x + b) & 0xFF
            elif ftype == 3:
                x = (x + ((a + b) >> 1)) & 0xFF
            elif ftype == 4:
                x = (x + paeth(a, b, c)) & 0xFF
            line[i] = x
        rows.append(line)
        prev = line

    pixels = []
    for y in range(height):
        line = rows[y]
        row = []
        for x in range(width):
            i = x * channels
            r = line[i]
            g = line[i + 1]
            bl = line[i + 2]
            al = line[i + 3] if channels == 4 else 255
            row.append((r, g, bl, al))
        pixels.append(row)

    return width, height, pixels


def area_resample(rows, width, height, out_w, out_h):
    out = []
    for oy in range(out_h):
        sy0 = oy * height // out_h
        sy1 = max(sy0 + 1, (oy + 1) * height // out_h)
        line = []
        for ox in range(out_w):
            sx0 = ox * width // out_w
            sx1 = max(sx0 + 1, (ox + 1) * width // out_w)
            sum_a = 0
            sum_r = sum_g = sum_b = 0
            n = 0
            for y in range(sy0, sy1):
                for x in range(sx0, sx1):
                    r, g, b, a = rows[y][x]
                    sum_a += a
                    sum_r += r * a
                    sum_g += g * a
                    sum_b += b * a
                    n += 1
            if n == 0:
                line.append((0, 0, 0, 0))
            elif sum_a == 0:
                line.append((0, 0, 0, 0))
            else:
                line.append((sum_r // sum_a, sum_g // sum_a, sum_b // sum_a,
                             sum_a // n))
        out.append(line)
    return out


def main():
    png = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_PNG

    width, height, rows = decode_png(png)
    small = area_resample(rows, width, height, ICON_W, ICON_H)

    packed = []
    for y in range(ICON_H):
        for x in range(ICON_W):
            r, g, b, a = small[y][x]
            packed.append((a << 24) | (r << 16) | (g << 8) | b)

    rel = os.path.relpath(png, ROOT).replace("\\", "/")

    with open(OUT_H, "w", newline="\n") as fh:
        fh.write("/* Auto-generated by tools/png2icon.py from %s. Do not edit. */\n"
                 % rel)
        fh.write("#ifndef EC_ICON_DATA_H\n")
        fh.write("#define EC_ICON_DATA_H\n\n")
        fh.write("#include <stdint.h>\n\n")
        fh.write("#define FOLDER_ICON_W %d\n" % ICON_W)
        fh.write("#define FOLDER_ICON_H %d\n\n" % ICON_H)
        fh.write("extern const uint32_t folder_icon_rgba[FOLDER_ICON_W * FOLDER_ICON_H];\n\n")
        fh.write("#endif\n")

    with open(OUT_C, "w", newline="\n") as fh:
        fh.write("/* Auto-generated by tools/png2icon.py from %s. Do not edit. */\n"
                 % rel)
        fh.write("#include \"icon_data.h\"\n\n")
        fh.write("const uint32_t folder_icon_rgba[FOLDER_ICON_W * FOLDER_ICON_H] = {\n")
        for y in range(ICON_H):
            base = y * ICON_W
            vals = ", ".join("0x%08Xu" % packed[base + x] for x in range(ICON_W))
            fh.write("    " + vals + (",\n" if y < ICON_H - 1 else "\n"))
        fh.write("};\n")

    print("  icon  %dx%d -> %s (from %s)"
          % (ICON_W, ICON_H, os.path.relpath(OUT_C, ROOT), rel))


if __name__ == "__main__":
    main()
