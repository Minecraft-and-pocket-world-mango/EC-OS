#!/usr/bin/env python3
"""
Generate system/font16x32.c for EC-OS.

The current source is the existing 8x8 bitmap in system/font.c.
Each 8x8 glyph is scaled x2 horizontally and x2 vertically into a
16x32 cell (centred, rows 8..23).  This keeps a crisp "pixel" look and
needs no external library.

Replace the SCALE function / source with a TTF rasteriser later if you
want a smoother font -- the output format stays the same:

    const uint16_t font16x32[96][32];
    row bit15 = leftmost pixel, bit0 = rightmost.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_C = ROOT / "system" / "font.c"
OUT_C = ROOT / "system" / "font16x32.c"

GLYPHS = 96
SRC_H = 8
SRC_W = 8
DST_H = 32
DST_W = 16


def load_font8x8():
    text = FONT_C.read_text()
    vals = [int(m, 16) for m in re.findall(r"0x([0-9A-Fa-f]{2})", text)]
    if len(vals) < GLYPHS * SRC_H:
        print(f"error: only found {len(vals)} bytes in {FONT_C}")
        sys.exit(1)
    vals = vals[: GLYPHS * SRC_H]
    return [vals[i * SRC_H:(i + 1) * SRC_H] for i in range(GLYPHS)]


def scale_glyph(rows):
    """8x8 -> 16x32 (2x horizontal, 2x vertical, vertically centred)."""
    out = [0] * DST_H
    top = (DST_H - SRC_H * 2) // 2          # 8 px top padding
    for r in range(SRC_H):
        line = 0
        byte = rows[r]
        for c in range(SRC_W):
            if byte & (1 << c):             # bit0 = leftmost in source
                line |= 0x8000 >> (2 * c)
                line |= 0x8000 >> (2 * c + 1)
        out[top + 2 * r] = line
        out[top + 2 * r + 1] = line
    return out


def main():
    glyphs = load_font8x8()
    lines = ['/* Auto-generated by tools/gen_font.py. Do not edit. */',
             '#include "font.h"',
             '',
             'const uint16_t font16x32[96][32] = {']
    for i, g in enumerate(glyphs):
        rows = scale_glyph(g)
        ch = chr(0x20 + i)
        disp = ch if 0x20 <= ord(ch) < 0x7F else '?'
        body = ", ".join(f"0x{v:04X}" for v in rows)
        lines.append(f"    {{ {body} }}, /* '{disp}' */")
    lines.append("};")
    lines.append("")
    OUT_C.write_text("\n".join(lines))
    print(f"  font16x32.c -> {OUT_C}  ({GLYPHS} glyphs)")


if __name__ == "__main__":
    main()
